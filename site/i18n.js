window.t = function t(key) {
  const lang = localStorage.getItem("hj-lang") || "en";
  const dict = (window.I18N[lang] || window.I18N.en);
  return dict[key] != null ? dict[key] : ((window.I18N.en || {})[key] || key);
};

window.applyI18n = function applyI18n(lang) {
  const dict = window.I18N[lang] || window.I18N.en;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.body.classList.toggle("lang-zh", lang === "zh");
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] != null) el.innerHTML = dict[key];
  });
  const btn = document.getElementById("lang-toggle");
  if (btn) {
    btn.textContent = dict["lang.btn"] || (lang === "zh" ? "EN" : "中文");
    btn.setAttribute("aria-pressed", lang === "zh" ? "true" : "false");
  }
  localStorage.setItem("hj-lang", lang);
  document.dispatchEvent(new CustomEvent("hj:lang", { detail: { lang } }));
};

window.initLangToggle = function initLangToggle() {
  const root = document.getElementById("lang-switch");
  const btn = document.getElementById("lang-toggle");
  let lang = localStorage.getItem("hj-lang") || "en";

  function syncSwitch(L) {
    if (root) {
      root.querySelectorAll("[data-lang]").forEach((el) => {
        el.classList.toggle("active", el.dataset.lang === L);
        el.setAttribute("aria-pressed", el.dataset.lang === L ? "true" : "false");
      });
    }
    if (btn) {
      btn.textContent = L === "zh" ? "EN" : "中文";
      btn.setAttribute("aria-pressed", L === "zh" ? "true" : "false");
    }
  }

  const _apply = window.applyI18n;
  window.applyI18n = function (L) {
    _apply(L);
    syncSwitch(L);
  };

  window.applyI18n(lang);
  syncSwitch(lang);

  if (root) {
    root.querySelectorAll("[data-lang]").forEach((el) => {
      el.addEventListener("click", () => {
        lang = el.dataset.lang;
        window.applyI18n(lang);
      });
    });
  } else if (btn) {
    btn.addEventListener("click", () => {
      lang = lang === "en" ? "zh" : "en";
      window.applyI18n(lang);
    });
  }
};
